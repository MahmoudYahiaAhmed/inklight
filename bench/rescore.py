"""Re-score saved predictions with the five-outcome definitions in bench/scoring.py.

    python bench/rescore.py bench/results/external

The original result files are read, never modified. For each one, a rescored summary is written to
``<dir>/rescored/<name>`` with the sha256 of the file it came from, and ``<dir>/rescored/tables.md`` lists
every run.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from scoring import OUTCOMES, outcome, summarize  # noqa: E402

BUILDS = {
    "A": "PyPI 0.1.0",
    "B": "before fixes (d0fac3d)",
    "C": "fix 1 (e08497b)",
    "D": "fix 2 (2794110)",
    "E": "pre-final (2f07058)",
    "F": "final (05206d7)",
    "G": "digit-loss v1 (e61a8d6)",
    "H": "amount check v2 (3788bf9)",
}
TASK_OUTCOMES = (
    "correct",
    "unnecessary_flag",
    "flagged",
    "silent_wrong",
    "useful_abstention",
    "failed_refusal",
    "crash",
    "timeout",
)


def rescore(path: Path) -> dict:
    raw = path.read_bytes()
    d = json.loads(raw)
    rows = [
        {**r, "outcome5": outcome(r["field"], r["got"], r["want"], r.get("warning"), r.get("confidence"))}
        for r in d["rows"]
    ]
    return {
        "source_file": path.name,
        "source_sha256": hashlib.sha256(raw).hexdigest(),
        "build": path.stem.split("-")[1],
        "dataset": d["dataset"],
        "genuine": d["genuine"],
        "split": d["split"],
        "brain_mode": d["brain_mode"],
        "input": d["input"],
        "provenance": d["provenance"],
        "extraction": summarize(rows),
        "rows": [
            {k: r[k] for k in ("doc", "field", "want", "got", "method", "warning", "confidence", "outcome5")}
            for r in rows
        ],
        "tasks": d.get("tasks"),  # schema 2 only; older files checked document sets, not results
    }


def pct(x: float | None) -> str:
    return "–" if x is None else f"{100 * x:.1f}%"


def table(items: list[dict]) -> str:
    head = (
        "| File | Build | Dataset | Split | Brain | n | Value accuracy | **Coverage without review** "
        "| **Precision, unflagged** | Silent errors | Review rate | Missing | " + " | ".join(OUTCOMES) + " |"
    )
    lines = [head, "|" + "---|" * (12 + len(OUTCOMES))]
    for s in items:
        o = s["extraction"]["overall"]
        kind = "genuine receipts" if s["genuine"] else "synthetic invoices"
        lines.append(
            f"| {s['source_file'].rsplit('-', 3)[0]} | {BUILDS.get(s['build'], s['build'])} "
            f"| {s['dataset']} ({kind}) | {s['split']} | {s['brain_mode']} | {o['n']} "
            f"| {pct(o['value_accuracy'])} | **{pct(o['coverage_without_review'])}** "
            f"| **{pct(o['precision_unflagged'])}** | {pct(o['silent_error_rate'])} | {pct(o['review_rate'])} "
            f"| {pct(o['missing_rate'])} | " + " | ".join(str(o["counts"][k]) for k in OUTCOMES) + " |"
        )
    return "\n".join(lines)


def tasks_table(items: list[dict]) -> str:
    head = "| File | Build | Dataset | Split | Brain | Kind | n | " + " | ".join(TASK_OUTCOMES) + " |"
    lines = [head, "|" + "---|" * (7 + len(TASK_OUTCOMES))]
    for s in items:
        task_items = (s.get("tasks") or {}).get("items") or []
        kinds = sorted({t["kind"] for t in task_items})
        for kind in kinds:
            ts = [t for t in task_items if t["kind"] == kind]
            counts = [sum(t["outcome"] == o for t in ts) for o in TASK_OUTCOMES]
            lines.append(
                f"| {s['source_file'].rsplit('-', 3)[0]} | {BUILDS.get(s['build'], s['build'])} | {s['dataset']} "
                f"| {s['split']} | {s['brain_mode']} | {kind} | {len(ts)} | " + " | ".join(map(str, counts)) + " |"
            )
    return "\n".join(lines)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("directory", type=Path)
    args = ap.parse_args()
    out = args.directory / "rescored"
    out.mkdir(exist_ok=True)
    items = []
    for path in sorted(args.directory.glob("*.json")):
        s = rescore(path)
        (out / path.name).write_text(json.dumps(s, indent=1, default=str), encoding="utf-8")
        items.append(s)
    (out / "tables.md").write_text(
        "# Rescored field results (five outcomes)\n\nGenerated by `bench/rescore.py` from the saved predictions; "
        "the original files are unchanged. Flagged = warning or confidence < 0.7.\n\n"
        + table(items)
        + "\n\n## Task-level results (runs with schema 2 only)\n\n"
        + tasks_table(items)
        + "\n",
        encoding="utf-8",
    )
    print(f"rescored {len(items)} files into {out}")


if __name__ == "__main__":
    main()
